import assert from 'node:assert/strict';
import test from 'node:test';
import { COMPLETENESS, aggregateAttempts, classifyCompleteness, classifyProviderFailure, isLiveExecutionAuthorized, mergeAttempt, normalizeSegments } from './benchmark-core.mjs';
import { contentOsPoProviderArgs, normalizeRaphaSrt, normalizeYoutubeTranscriptApiOutput, normalizeYTranscriptOutput, normalizeYtDlpVtt } from './provider-runners.mjs';

const repeated = (text, count) => Array.from({ length: count }, (_, index) => ({ text: `${text} ${index} with substantive discussion and context`, startMs: index * 60_000, durationMs: 40_000 }));

test('normalizes seconds-based timestamp segments', () => {
  assert.deepEqual(normalizeSegments([{ text: 'Words', start: 4, duration: 2 }]), [{ text: 'Words', startMs: 4000, durationMs: 2000 }]);
});
test('classifies an end-only advertisement as incomplete for a ten-minute video', () => {
  const result = classifyCompleteness({ outcome: 'success', videoDurationMs: 600_000, segments: repeated('Career promotion', 10).map((segment, index) => ({ ...segment, startMs: 540_000 + index * 5_000, durationMs: 4_000 })) });
  assert.equal(result.classification, COMPLETENESS.INCOMPLETE);
  assert.match(result.reason, /starts_too_late|coverage/);
});
test('classifies an early-to-late substantive transcript as complete', () => {
  const result = classifyCompleteness({ outcome: 'success', videoDurationMs: 600_000, segments: repeated('Nepal flood rescue discussion', 10) });
  assert.equal(result.classification, COMPLETENESS.COMPLETE);
});
test('does not claim complete without a duration authority', () => {
  const result = classifyCompleteness({ outcome: 'success', segments: repeated('Substantive transcript', 10) });
  assert.equal(result.classification, COMPLETENESS.UNKNOWN);
});
test('keeps no captions distinct from operational failures', () => {
  assert.equal(classifyCompleteness({ outcome: 'no_captions', segments: [] }).classification, COMPLETENESS.NO_CAPTIONS);
  assert.equal(classifyProviderFailure(new Error('HTTP Error 429: Too Many Requests')), 'rate_limited');
  assert.equal(classifyProviderFailure(new Error('Sign in to confirm you are not a bot')), 'bot_challenge');
});
test('checkpoint merge replaces an attempt by provider and video identity', () => {
  const first = mergeAttempt({ attempts: [] }, { provider: 'a', videoId: '12345678901', durationMs: 1 });
  const second = mergeAttempt(first, { provider: 'a', videoId: '12345678901', durationMs: 2 });
  assert.equal(second.attempts.length, 1); assert.equal(second.attempts[0].durationMs, 2);
});
test('aggregates latency and complete versus incomplete attempts independently', () => {
  const aggregate = aggregateAttempts([{ provider: 'a', completeness: 'complete', durationMs: 100 }, { provider: 'a', completeness: 'incomplete', durationMs: 300 }]).a;
  assert.deepEqual({ complete: aggregate.complete, incomplete: aggregate.incomplete, p50: aggregate.p50LatencyMs, p95: aggregate.p95LatencyMs }, { complete: 1, incomplete: 1, p50: 100, p95: 300 });
});
test('uses ContentOS non-secret script-provider arguments only when explicitly enabled', () => {
  assert.deepEqual(contentOsPoProviderArgs({ YOUTUBE_PO_TOKEN_PROVIDER_ENABLED: 'true', YOUTUBE_PO_TOKEN_PROVIDER_MODE: 'script', YOUTUBE_PO_TOKEN_PROVIDER_PATH: 'C:\\provider', YOUTUBE_JS_RUNTIME: 'node' }), ['--js-runtimes', 'node', '--extractor-args', 'youtubepot-bgutilscript:server_home=C:\\provider']);
  assert.deepEqual(contentOsPoProviderArgs({}), []);
});
test('normalizes local VTT, SRT, Python, and Node fixtures with Hindi Unicode intact', () => {
  const subtitle = 'WEBVTT\n\n00:00:04.000 --> 00:00:07.000\nनमस्कार, मैं हूं प्रशांत धवन।\n\n00:00:07.000 --> 00:00:10.000\nThis is Hinglish context.';
  const expected = [{ text: 'नमस्कार, मैं हूं प्रशांत धवन।', startMs: 4000, durationMs: 3000 }, { text: 'This is Hinglish context.', startMs: 7000, durationMs: 3000 }];
  assert.deepEqual(normalizeYtDlpVtt(subtitle), expected);
  assert.deepEqual(normalizeRaphaSrt(subtitle.replace('WEBVTT\n\n', '1\n')), expected);
  assert.deepEqual(normalizeYoutubeTranscriptApiOutput({ language: 'hi', captionType: 'automatic', segments: expected }).segments, expected);
  assert.deepEqual(normalizeYTranscriptOutput({ language: 'hi', isAutoGenerated: true, segments: expected }).segments, expected);
});
test('does not authorize a live benchmark unless the explicit flag is supplied', () => {
  assert.equal(isLiveExecutionAuthorized({}), false);
  assert.equal(isLiveExecutionAuthorized({ live: 'true' }), true);
});
test('treats malformed provider output as no normalized transcript rather than inventing segments', () => {
  assert.deepEqual(normalizeYTranscriptOutput({ language: 'hi', isAutoGenerated: true, segments: [{ text: '', start: 'not-a-time', duration: -1 }] }).segments, []);
  assert.deepEqual(normalizeYoutubeTranscriptApiOutput({ language: 'hi', captionType: 'automatic', segments: null }).segments, []);
});
